"""Evidence for promote and rollback, on a throwaway copy of the version registry.

The real versions/ folder is left alone, because promotion is a decision for a person. This script
copies it, promotes the accepted candidate, shows behaviour change, rolls back, and shows the old
behaviour returns byte for byte.
"""
from __future__ import annotations

import hashlib
import json
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from riskwatch.config import Paths  # noqa: E402
from riskwatch.controller import Controller, Env  # noqa: E402
from riskwatch.improve import versions  # noqa: E402
from riskwatch.pit import PointInTimeStore  # noqa: E402

DAY = "2020-03-16"
ACTOR = "demo-script (not a human decision)"


def run_day(paths: Paths, store: PointInTimeStore, home: Path) -> dict:
    """Run one day on whatever version is active, in its own home."""
    run_paths = Paths(paths.root, home, paths.versions, paths.data)
    version = versions.active(paths)
    env = Env(run_paths, versions.load_snapshot(paths, version), version, store=store, mode="replay", durable=False)
    ctl = Controller(env)
    ctl.create_run(f"eod-{DAY}", "eod", DAY, f"{DAY}T20:00", "demo")
    ctl.drive(f"eod-{DAY}")
    folder = home / "artifacts" / f"eod-{DAY}"
    metrics = json.loads((folder / "metrics.json").read_text(encoding="utf-8"))
    digest = hashlib.sha256((folder / "metrics.json").read_bytes()).hexdigest()
    env.close()
    return {"version": version, "var99_1d": metrics["var99_1d"]["value"], "metrics_sha256": digest}


def main() -> None:
    accepted = [e for e in versions.history(Paths(ROOT, ROOT, ROOT / "versions", ROOT))
                if e["event"] == "evaluated" and e["decision"] == "accept"]
    if not accepted:
        sys.exit("no accepted candidate to demonstrate with")
    candidate = accepted[-1]["version"]
    store = PointInTimeStore(ROOT / "data" / "feed")

    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        shutil.copytree(ROOT / "versions", tmp / "versions")
        paths = Paths(ROOT, tmp, tmp / "versions", ROOT / "data" / "feed")

        before = run_day(paths, store, tmp / "a")
        rejected = [e["version"] for e in versions.history(paths) if e["event"] == "evaluated" and e["decision"] == "reject"]
        refused = ""
        try:
            versions.promote(paths, rejected[0], ACTOR)
        except versions.VersionError as e:
            refused = str(e)

        versions.promote(paths, candidate, ACTOR)
        promoted = run_day(paths, store, tmp / "b")
        target = versions.rollback(paths, ACTOR, "demonstration of rollback")
        after = run_day(paths, store, tmp / "c")
        events = [e for e in versions.history(paths) if e["event"] in ("promoted", "rolled_back")]

    ok = (before["metrics_sha256"] == after["metrics_sha256"] and promoted["var99_1d"] != before["var99_1d"]
          and target == before["version"] and bool(refused))
    lines = [f"# Promote and rollback demonstration ({'PASSED' if ok else 'FAILED'})", "",
             "Generated by `scripts/demo_version_cycle.py` on a temporary copy of `versions/`, so the real active",
             f"version did not change. The decisions below are by `{ACTOR}`.", "",
             f"Each step runs {DAY} on the active version.", "",
             "| Step | Active version | 1-day 99% VaR | metrics.json SHA-256 |", "|---|---|---|---|"]
    for name, r in (("Before", before), ("After promotion", promoted), ("After rollback", after)):
        lines.append(f"| {name} | `{r['version']}` | {r['var99_1d']:.4%} | `{r['metrics_sha256'][:16]}...` |")
    lines += ["", "Promoting a rejected candidate was refused with:", "", f"> {refused}", "",
              "Registry events written:", "", "```json"] + [json.dumps(e, sort_keys=True) for e in events] + ["```"]
    out = ROOT / "evidence" / "versioning"
    out.mkdir(parents=True, exist_ok=True)
    (out / "promote_rollback.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("PASSED" if ok else "FAILED")
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
