"""Leakage evidence: the future-perturbation test on key days, plus a negative control that must fail."""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from riskwatch.config import default_paths  # noqa: E402
from riskwatch.improve import versions  # noqa: E402
from riskwatch.improve.leakage import negative_control, perturbation_test  # noqa: E402
from riskwatch.pit import PointInTimeStore  # noqa: E402

DAYS = ["2019-11-05", "2020-01-16", "2020-02-24", "2020-03-09", "2020-03-16", "2020-04-09", "2020-05-12"]


def main() -> None:
    paths = default_paths()
    version = versions.active(paths)
    bundle = versions.load_snapshot(paths, version)
    store = PointInTimeStore(ROOT / "data" / "feed")
    result = perturbation_test(bundle, version, ROOT, store, DAYS)
    control = negative_control(bundle, version, ROOT, store, "2020-03-16")
    ok = result["passed"] and control["leak_detected"]

    lines = [f"# Future-perturbation test ({'PASSED' if ok else 'FAILED'})", "",
             f"Version `{version}`. Generated by `scripts/demo_leakage.py`.", "",
             "For each day, the run is repeated with every row published after its cutoff corrupted: returns set to -90%,",
             "weights to 50%, NAV to 1. If the run used none of that data, every artifact is byte-identical.", "",
             "| Day | Artifacts compared | Identical |", "|---|---|---|"]
    lines += [f"| {r['day']} | {r['files']} | {r['identical']} |" for r in result["days"]]
    lines += ["", "**Negative control.** The same comparison through a store with its cutoff filter disabled must show a",
              f"difference, or this test could not catch a leak. Day {control['day']}: leak detected = {control['leak_detected']}."]
    out = ROOT / "evidence" / "leakage"
    out.mkdir(parents=True, exist_ok=True)
    (out / "perturbation_report.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("PASSED" if ok else "FAILED")
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
